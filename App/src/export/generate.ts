/**
 * The two ExtendScript generators.
 *
 * The split is the one Kyle asked for, and it is a build/link split rather than two unrelated
 * exporters:
 *
 *   PACKAGE  every catalogue asset becomes its own comp, saved once into a standalone
 *            `Win95Assets.aep`. Expensive, run rarely.
 *   SCENE    a layout becomes a scene comp whose layers *reference* comps from that package.
 *            Cheap, run constantly.
 *
 * The mechanism underneath is `project.save(file)` on one side and `importFile` with
 * `ImportAsType.PROJECT` on the other — the AE spike proved that round trip: a saved `.aep`
 * re-imports into a different project as a single folder containing every comp intact.
 *
 * Both scripts are ES3, both embed their data as object literals (there is no `JSON` in
 * ExtendScript), and both share `ES3_RUNTIME`.
 */

