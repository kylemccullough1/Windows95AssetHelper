/** Comp name for a catalogue asset. The scene script resolves package comps by this exact name. */
export function assetCompName(assetId: string): string {
  return `Icon - ${assetId}`
}

/** Folder the package builds into, and the folder the scene script looks inside. */
export const PACKAGE_FOLDER = 'Win95 Assets'

/** Rectangles grouped by colour, in the compact shape the ES3 runtime consumes. */
type EmittedLayer = { k: string; c: readonly number[]; r: number[][] }

function emitChromeLayers(rects: ChromeRect[]): EmittedLayer[] {
  // One AE group per colour rather than per rectangle: far fewer groups, and it matches how the
  // icon geometry is already organised, so the runtime needs only one code path.
  const byColor = new Map<string, number[][]>()
  for (const rect of rects) {
    const bucket = byColor.get(rect.color)
    if (bucket) bucket.push([rect.x, rect.y, rect.w, rect.h])
    else byColor.set(rect.color, [[rect.x, rect.y, rect.w, rect.h]])
  }
  return [...byColor.entries()].map(([color, r]) => ({ k: color, c: toRgb(color), r }))
}

function emitIconLayers(icon: IconGeometry): EmittedLayer[] {
  return icon.layers.map((layer) => ({
    k: layer.color,
    c: toRgb(layer.color),
    r: layer.rects.map((rect) => [rect.x, rect.y, rect.w, rect.h]),
  }))
}

function header(title: string, extra: string[] = []): string {
  const lines = [
    `// ${title}`,
    '//',
    '// Generated by the Windows 95 Asset Studio. Do not edit by hand - re-export instead.',
    `// Generated ${new Date().toISOString()}`,
    '//',
    ...extra.map((line) => `// ${line}`),
    '',
    '#target aftereffects',
  ]
  return lines.join('\n')
}

