// Resolve every asset comp this scene needs. If any are absent, import the package.
function resolveAssets() {
    var missing = [];
    var i;
    for (i = 0; i < REQUIRED.length; i++) {
        if (findComp(REQUIRED[i]) === null) { missing.push(REQUIRED[i]); }
    }
    if (missing.length === 0) { return true; }

    var aep;
    if (PACKAGE_PATH !== null) {
        aep = new File(PACKAGE_PATH);
        if (!aep.exists) { log("package not found at " + PACKAGE_PATH); return false; }
    } else {
        var answer = confirm(missing.length + " asset comp(s) are not in this project.\\n\\n" +
                             "Locate Win95Assets.aep to import the asset package?");
        if (!answer) { return false; }
        aep = File.openDialog("Select Win95Assets.aep", "After Effects Project:*.aep");
        if (aep === null) { return false; }
    }

    var io = new ImportOptions(aep);
    io.importAs = ImportAsType.PROJECT;   // lands as a folder holding every comp
    app.project.importFile(io);
    log("imported package from " + aep.fsName);

    missing = [];
    for (i = 0; i < REQUIRED.length; i++) {
        if (findComp(REQUIRED[i]) === null) { missing.push(REQUIRED[i]); }
    }
    if (missing.length > 0) {
        log("still missing after import: " + missing.join(", "));
        if (PACKAGE_PATH === null) {
            alert("Still missing after import:\\n" + missing.join("\\n") +
                  "\\n\\nRe-export the asset package so it includes these.");
        }
        return false;
    }
    return true;
}

function buildWindowComp(folder, win, font) {
    var comp = app.project.items.addComp("Window - " + win.title, win.w, win.h, 1.0, SCENE.fps, SCENE.duration);
    comp.parentFolder = folder;

    // Frame, bevels, title bar and button faces: one shape layer, one group per colour.
    var chrome = addShapeLayer(comp, "Chrome");
    var contents = contentsOf(chrome);
    for (var i = 0; i < win.frame.length; i++) {
        addColorGroup(contents, win.frame[i].k, win.frame[i].c, win.frame[i].r);
    }

    // The close glyph, offset to the button's position.
    var glyph = addShapeLayer(comp, "Close glyph");
    var gc = contentsOf(glyph);
    var moved = [];
    for (var g = 0; g < win.glyph.r.length; g++) {
        var r = win.glyph.r[g];
        moved.push([r[0] + win.glyph.x, r[1] + win.glyph.y, r[2], r[3]]);
    }
    addColorGroup(gc, "glyph", GLYPH_RGB, moved);

    // Title bar icon: a layer referencing the package comp, so the asset stays independent.
    if (win.icon !== null) {
        var iconComp = findComp(win.icon);
        if (iconComp !== null) {
            var iconLayer = comp.layers.add(iconComp);
            iconLayer.name = win.icon;
            iconLayer.property("ADBE Transform Group").property("ADBE Position")
                .setValue(centreOf(win.iconPos.x, win.iconPos.y, iconComp.width, iconComp.height));
        }
    }

    addTextLayer(comp, win.title, FONT_PS, font, TITLE_SIZE, TITLE_RGB, win.textX, win.textBaseline);
    return comp;
}

function main() {
    var started = new Date();
    // Before resolveAssets, which imports the package into whatever project is current. Doing
    // this after would import into the user's project and then throw it away.
    if (PROJECT_PATH !== null) { app.newProject(); }
    if (!resolveAssets()) { return; }

    app.beginUndoGroup("Build Win95 scene");
    var suppressed = (LOG_PATH !== null) && suppressDialogs(true);
    var font = findFont(FONT_PS);
    log("scene build; app.version=" + app.version + " font=" + (font === null ? "NOT FOUND (" + FONT_PS + ")" : "ok"));

    var root = findFolder("Win95 Scenes");
    if (root === null) { root = app.project.items.addFolder("Win95 Scenes"); }
    var sceneFolder = app.project.items.addFolder(SCENE.name);
    sceneFolder.parentFolder = root;
    var winFolder = app.project.items.addFolder("Windows");
    winFolder.parentFolder = sceneFolder;

    var scene = app.project.items.addComp("Scene - " + SCENE.name, SCENE.w, SCENE.h, 1.0, SCENE.duration, SCENE.fps);
    scene.parentFolder = sceneFolder;

    // Desktop background, locked so it is never dragged by accident.
    var desk = scene.layers.addSolid(SCENE.bg, "Desktop", SCENE.w, SCENE.h, 1.0);
    desk.locked = true;

    // Placed icons, each referencing its package comp.
    var i;
    for (i = 0; i < ICONS.length; i++) {
        var spec = ICONS[i];
        var assetComp = findComp(spec.comp);
        if (assetComp === null) { log("MISSING " + spec.comp); continue; }
        var layer = scene.layers.add(assetComp);
        layer.name = spec.comp;
        layer.property("ADBE Transform Group").property("ADBE Position")
            .setValue(centreOf(spec.x, spec.y, assetComp.width, assetComp.height));
        layer.comment = "icon:" + spec.comp;
        if (spec.label !== "") {
            addTextLayer(scene, spec.label, FONT_PS, font, TITLE_SIZE, TITLE_RGB,
                         spec.x, spec.y + assetComp.height + 12);
        }
    }

    // Windows, back to front: WINDOWS is already sorted by z ascending, and each new layer
    // lands on top of the previous one, so the stack matches the scene with no reordering.
    for (i = 0; i < WINDOWS.length; i++) {
        var win = WINDOWS[i];
        var winComp = buildWindowComp(winFolder, win, font);
        var winLayer = scene.layers.add(winComp);
        winLayer.name = win.title;
        winLayer.property("ADBE Transform Group").property("ADBE Position")
            .setValue(centreOf(win.x, win.y, win.w, win.h));
        winLayer.comment = "window:" + win.id;
        winLayer.moveToBeginning();
    }

    if (SCENE.taskbar) {
        var bar = addShapeLayer(scene, "Taskbar");
        addColorGroup(contentsOf(bar), "face", TASKBAR_RGB,
                      [[0, SCENE.h - TASKBAR_H, SCENE.w, TASKBAR_H]]);
        bar.moveToBeginning();
    }

    if (suppressed) { suppressDialogs(false); }
    app.endUndoGroup();
    scene.openInViewer();

    // The finished project, at the path the user browsed to. Saved after endUndoGroup so the
    // file on disk is the completed scene rather than a half-built one.
    if (PROJECT_PATH !== null) {
        var out = new File(PROJECT_PATH);
        if (out.parent !== null && !out.parent.exists) { out.parent.create(); }
        app.project.save(out);
        log("saved " + out.fsName + " (" + out.length + " bytes)");
    }

    log("done in " + ((new Date()).getTime() - started.getTime()) + " ms");
}

// Same rule as the package script: unattended runs write a log, never a modal dialog.
function finish() {
    if (LOG_PATH !== null) { writeLog(new Folder(LOG_PATH), "win95-scene-log.txt"); }
}

try { main(); finish(); }
catch (err) {
    log("FAILED " + err.toString() + " line " + err.line);
    finish();
    if (LOG_PATH === null) {
        alert("Scene export FAILED\\n" + err.toString() + "\\nline " + err.line + "\\n\\n" + LOG.join("\\n"));
    }
}
